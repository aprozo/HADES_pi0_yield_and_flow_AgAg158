Bool_t isBorderCell(const Int_t & cell)
{
	for (Int_t i=0; i<30; i++) {
		if (side_border_cells[i]==cell) return true;
	}
	return false;
}

Int_t getRow(const Int_t & cell) {
	return cellMap[cell]/17;
}

Int_t getColumn(const Int_t & cell) {
	return cellMap[cell]%17;
}

Float_t getDistance(const Int_t & cell1,const Int_t & cell2){
	Float_t dCol = getColumn(cell1) -  getColumn(cell2);
	Float_t dRow = getRow(cell1)    - getRow(cell2);
	return TMath::Sqrt(dCol*dCol+dRow*dRow);
}


Char_t dColumn[8] = {-1,+1,  0, 0, -1,-1, +1,+1};
Char_t dRow[8]    = { 0, 0, -1,+1, -1,+1, -1,+1};

Int_t getNearbyCell(Int_t cell,Int_t i) {

	Int_t row    = cellMap[cell]/17 + dRow[i];
	if(row<0    || row>=15) return -1;

	Int_t column = cellMap[cell]%17 + dColumn[i];
	if(column<0 || column>=17) return -1;

	return systemMap[row*17 + column];
}


Int_t isGoodCell(const Int_t & sector,const Int_t & cell)
{
	if (cell<10) return 0;
	if (sector==0||sector==3) return 0;

	if (goodcellMap[sector][cell]!=-1) return 1;
	return 0;
}

